/**
 * Tema de la app con los colores de marca del fundo (verde y dorado) en modo claro y oscuro.
 * No usa los colores dinamicos de Android 12+ para que la app se vea igual en todos los telefonos
 * y los colores del semaforo (verde, ambar, rojo) no cambien de significado.
 */
@Composable
fun MyApplicationTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    CompositionLocalProvider(LocalStatusColors provides if (darkTheme) DarkStatusColors else LightStatusColors) {
        MaterialTheme(
            colorScheme = if (darkTheme) DarkColors else LightColors,
            typography = Typography,
            content = content
        )
    }
}
